#!/usr/bin/env python3
"""Build on Windows x64, never disguise a Linux executable as an .exe.

Creates an isolated build environment, runs the tests, bundles Python/Tk, and
checks the produced program before creating a portable ZIP. No administrator
rights are needed. Installing the pinned build dependency requires network
access unless pip's cache / a configured local package index provides it.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import shutil
import struct
import subprocess
import sys
import tempfile
import venv

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from classiccalc import __version__

NAME = "KlassischerRechner"


def command(args: list[str | Path], **kwargs) -> None:
    args = [str(a) for a in args]
    print("\n> " + subprocess.list2cmdline(args), flush=True)
    subprocess.run(args, cwd=ROOT, check=True, **kwargs)


def write_version_resource(path: Path) -> None:
    """German version metadata for Explorer; trusted constants, not user code."""
    version = tuple(int(part) for part in __version__.split(".")) + (0,)
    path.parent.mkdir(parents=True, exist_ok=True)
    content = f'''# UTF-8; generated by tools/build_windows.py
VSVersionInfo(
  ffi=FixedFileInfo(filevers={version!r}, prodvers={version!r},
    mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[StringFileInfo([StringTable('040704B0', [
    StringStruct('CompanyName', 'Classic Calc contributors'),
    StringStruct('FileDescription', 'Klassischer Rechner'),
    StringStruct('FileVersion', '{__version__}'),
    StringStruct('InternalName', '{NAME}'),
    StringStruct('OriginalFilename', '{NAME}.exe'),
    StringStruct('ProductName', 'Klassischer Rechner'),
    StringStruct('ProductVersion', '{__version__}'),
    StringStruct('LegalCopyright', 'Copyright (c) 2026 Classic Calc contributors; MIT')
  ])]), VarFileInfo([VarStruct('Translation', [1031, 1200])])]
)
'''
    path.write_text(content, encoding="utf-8")


def smoke_check(executable: Path) -> dict:
    with tempfile.TemporaryDirectory(prefix="classic-calc-check-") as folder:
        report = Path(folder) / "report.json"
        command([executable, "--smoke-test", report], timeout=60)
        result = json.loads(report.read_text(encoding="utf-8"))
        if not (result.get("ok") and result.get("platform") == "win32"
                and result.get("bits") == 64 and result.get("version") == __version__):
            raise RuntimeError(f"EXE-Selbstprüfung fehlgeschlagen: {result}")
        return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Windows-x64-EXE und portables ZIP erstellen")
    parser.add_argument("--onefile", action="store_true", help="eine EXE statt eines Programmordners")
    parser.add_argument("--skip-tests", action="store_true", help="nur Unit-/GUI-Suite überspringen; EXE-Prüfung bleibt aktiv")
    parser.add_argument("--offline", action="store_true", help="keine pip-Installation; vorbereitete .venv-build verwenden")
    args = parser.parse_args(argv)
    if sys.platform != "win32":
        parser.error("Ein Windows-Build muss unter Windows laufen. Dieses Skript erzeugt unter Linux keine Windows-EXE.")
    if struct.calcsize("P") != 8:
        parser.error("CPython x64 ist erforderlich, nicht Python 32 Bit.")
    if not (3, 10) <= sys.version_info[:2] <= (3, 13):
        parser.error("Für diesen Build Python 3.10 bis 3.13 verwenden, empfohlen: py -3.13 tools\\build_windows.py")
    import tkinter  # Fail before downloading anything when Tcl/Tk is missing.
    if float(tkinter.TkVersion) < 8.6:
        parser.error("Tk 8.6 oder neuer wird benötigt.")
    env = ROOT / ".venv-build"
    python = env / "Scripts" / "python.exe"
    if not python.exists():
        if args.offline:
            parser.error("--offline benötigt eine vorbereitete .venv-build mit PyInstaller.")
        print("Erzeuge isolierte Build-Umgebung ...", flush=True)
        venv.EnvBuilder(with_pip=True).create(env)
    if not args.offline:
        command([python, "-m", "pip", "install", "-r", ROOT / "requirements-build.txt"])
    else:
        command([python, "-c", "import PyInstaller; assert PyInstaller.__version__ == '6.16.0'"])
    if not args.skip_tests:
        command([python, "-m", "unittest", "discover", "-v"], timeout=300)
    build = ROOT / "build" / "windows"
    dist = ROOT / "dist"
    metadata = build / "version_info.txt"
    write_version_resource(metadata)
    command([python, "-m", "PyInstaller", "--noconfirm", "--clean", "--noconsole", "--noupx",
             "--onefile" if args.onefile else "--onedir", "--name", NAME,
             "--icon", ROOT / "assets" / "classic-calc.ico",
             "--manifest", ROOT / "packaging" / "windows" / "app.manifest",
             "--version-file", metadata, "--distpath", dist,
             "--workpath", build / "pyinstaller", "--specpath", build,
             ROOT / "app.pyw"])
    program = dist / (NAME + ".exe") if args.onefile else dist / NAME / (NAME + ".exe")
    result = smoke_check(program)
    report_file = dist / "windows-smoke-results.json"
    report_file.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    kind = "onefile" if args.onefile else "portable"
    stem = f"KlassischerRechner-{__version__}-windows-x64-{kind}"
    with tempfile.TemporaryDirectory(prefix="classic-calc-package-") as folder:
        stage = Path(folder) / NAME
        if args.onefile:
            stage.mkdir()
            shutil.copy2(program, stage / program.name)
        else:
            shutil.copytree(program.parent, stage)
        for filename in ("LICENSE", "README.md", "CHANGELOG.md", "PORTING_NOTES.md"):
            shutil.copy2(ROOT / filename, stage / filename)
        shutil.copytree(ROOT / "screenshots", stage / "screenshots")
        shutil.copy2(ROOT / "WINDOWS-START.txt", stage / "WINDOWS-START.txt")
        shutil.copy2(report_file, stage / report_file.name)
        archive = Path(shutil.make_archive(str(dist / stem), "zip", folder))
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    archive.with_suffix(".zip.sha256").write_text(f"{digest}  {archive.name}\n", encoding="ascii")
    print(f"\nFertig: {program}\nPaket: {archive}")
    print("Der gesamte portable Ordner ist erforderlich; die Onefile-Variante bündelt ihn in einer EXE.")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, subprocess.SubprocessError, RuntimeError, ValueError) as exc:
        print(f"Build fehlgeschlagen: {exc}", file=sys.stderr)
        raise SystemExit(1)
